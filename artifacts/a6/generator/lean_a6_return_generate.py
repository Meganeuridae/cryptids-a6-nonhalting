"""Generate kernel-checked ordinary, cycle, and semantic A6 return certificates.
The JSON is untrusted proof input; all generated statements require Lean checks.
Finite Exit.valid proofs are generated by lean_a6_return_valid_generate.py.
"""
from pathlib import Path
import copy
import json

ROOT = Path(__file__).resolve().parents[1]
TRACE = ROOT/'results/ack6-lean-return-trace.json'
OUT = ROOT/'lean/A6/ReturnGenerated'
WORDS = {}

def wid(w):
    key=tuple(w)
    if key not in WORDS: WORDS[key]=len(WORDS)
    return WORDS[key]

def nat_aff(c, var='k'):
    a,b=c; b+=8*a
    assert a>=0 and b>=0,c
    return str(b) if not a else f'({a}*{var}+{b})'

def nat_aff2(c):
    a,b,v=c; v+=8*a
    assert a>=0 and v>=0,c
    base=str(v) if not a else f'{a}*k+{v}'
    if b>0: base+=f'+{b}*j'
    if b<0: base+=f'-{-b}*j'
    return '('+base+')' if a or b else base

def bits(w):
    return '['+','.join('true' if (x>>i)&1 else 'false' for x in w for i in (1,0))+']'

def word(w):return f'w{wid(w)}'

def stack(runs, cycle=False):
    aff=nat_aff2 if cycle else nat_aff
    return '['+','.join('⟨'+word(w)+','+aff(c)+'⟩' for w,c in reversed(runs))+']'

def cfg(s, cycle=False):
    if cycle:
        a,b,c=s['head'];head=f'({2*a}*(k:Int)+{2*b}*(j:Int)+{1+2*(c+8*a)})'
    else:
        a,b=s['head'];head=f'({2*a}*(k:Int)+{1+2*(b+8*a)})'
    return '⟨'+','.join([str(s['q']),str(s['d']==1).lower(),head,stack(s['left'],cycle),stack(s['right'],cycle)])+'⟩'

def exit_e(case):
    (w,q,d),(v,q1,d1,dt)=case
    return '⟨'+','.join([word(w),word(v),str(q),str(d==1).lower(),str(q1),str(d1==1).lower(),str(dt)])+'⟩'

def add(a,b):return tuple(x+y for x,y in zip(a,b))
def sub(a,b):return tuple(x-y for x,y in zip(a,b))
def scale(a,n):return tuple(x*n for x in a)

def cycle_data(cmd,cases):
    cert=cmd['certificate'];s=copy.deepcopy(cmd['before'])
    s['head']=(s['head'][0],cert['head'],s['head'][1]);ds=iter(cert['deltas'])
    for name in ('left','right'):
        s[name]=[[w,(c[0],next(ds),c[1])] for w,c in s[name]]
    initial=copy.deepcopy(s);steps=[]
    for _ in range(cert['length']):
        before=copy.deepcopy(s);src=s['right'] if s['d']==1 else s['left']
        w,c=src[-1] if src else ([0],(0,0,1))
        ei,(v,q,d,dt)=cases[(tuple(w),s['q'],s['d'])]
        n=c if (q,d)==(s['q'],s['d']) else (0,0,1)
        if src:
            rest=sub(src[-1][1],n)
            if rest==(0,0,0):src.pop()
            else:src[-1][1]=rest
        dst=s['left'] if d==1 else s['right']
        if n!=(0,0,0) and (dst or any(v)):
            if dst and tuple(dst[-1][0])==tuple(v):dst[-1][1]=add(dst[-1][1],n)
            else:dst.append([v,n])
        if d==s['d']:s['head']=add(s['head'],scale(n,d*len(w)))
        s['q'],s['d']=q,d;steps.append((before,copy.deepcopy(s),ei,n,dt))
    expected=copy.deepcopy(initial)
    expected['head']=(initial['head'][0],initial['head'][1],initial['head'][2]+initial['head'][1])
    for name in ('left','right'):
        expected[name]=[[w,(c[0],c[1],c[2]+c[1])] for w,c in expected[name]]
    for key in ('q','d','head','left','right'):assert s[key]==expected[key],(key,s[key],expected[key])
    duration=tuple(sum(n[t]*dt for _,_,_,n,dt in steps) for t in range(3))
    assert duration==(0,0,cert['steps']),duration
    delta=sub(cmd['after']['steps'],cmd['before']['steps'])
    assert all(t%cert['steps']==0 for t in delta)
    count=tuple(t//cert['steps'] for t in delta)
    return initial,steps,count

def collect(data):
    # Preserve this traversal so ReturnIdentity can refer to stable word ids.
    pairs=set()
    for case in data['cases']:wid(case[0][0]);wid(case[1][0])
    for cmd in data['commands']:
        for s in (cmd['before'],cmd['after']):
            for w,c in s['left']+s['right']:wid(w)
        if cmd['kind']!='word':continue
        (w,q,d),(v,q1,d1,dt)=data['cases'][cmd['case']]
        s=cmd['before'];l=s['left'][:];r=s['right'][:];src=r if d==1 else l
        if src and src[-1][1]==cmd['count']:src.pop()
        dst=l if d1==1 else r
        if dst:
            i,j=wid(dst[-1][0]),wid(v)
            if i!=j:pairs.add((i,j))
    return pairs

def header(imports):
    return [*(f'import {x}' for x in imports),'namespace A6.ReturnGenerated','open RLE',*(['attribute [local irreducible] A6.run RLE.Cfg.denote'] if imports!=['A6.RLE'] else []),'set_option maxRecDepth 100000','set_option maxHeartbeats 20000000','set_option linter.unusedVariables false','set_option linter.unusedSimpArgs false']

def write(name,lines):
    path=OUT/(name+'.lean');content='\n'.join(lines+['end A6.ReturnGenerated'])+'\n'
    if not path.exists() or path.read_text()!=content:path.write_text(content)

def compose(rows):
    """Explicit balanced transitivity avoids expensive Lean metavariable search."""
    if len(rows)==1:return rows[0]
    mid=len(rows)//2
    lt,ls,le,lp=compose(rows[:mid]);rt,rs,re,rp=compose(rows[mid:])
    return (f'({lt}+{rt})',ls,re,f'(@Runs.trans {lt} {rt} {ls} {le} {re} {lp} {rp})')


def main(limit=10000,chunk=100):
    data=json.loads(TRACE.read_text());OUT.mkdir(exist_ok=True);pairs=collect(data)
    lines=header(['A6.RLE'])
    for w,i in WORDS.items():
        lines += [f'def w{i} : Word := {bits(w)}',f'@[simp] theorem length{i} : w{i}.length = {2*len(w)} := by decide',f'@[simp] theorem blank{i} : w{i}.all (! ·) = {str(all(x==0 for x in w)).lower()} := by decide']
    lines += [f'@[simp] theorem implicitBlank : ([false,false] : Word) = w{WORDS[(0,)]} := rfl']
    for i,j in sorted(pairs):
        lines += [f'@[simp] theorem neq{i}_{j} : w{i} ≠ w{j} := by decide',f'@[simp] theorem beq{i}_{j} : (w{i} == w{j}) = false := by decide']
    for i,case in enumerate(data['cases']):lines += [f'def exit{i} : Exit := {exit_e(case)}']
    lines += [f'def initialCfg (k : Nat) : Cfg := {cfg(data["initial"])}',f'def endingCfg (k : Nat) : Cfg := {cfg(data["final"])}']
    write('Defs',lines)
    cases={(tuple(w),q,d):(i,result) for i,((w,q,d),result) in enumerate(data['cases'])}
    chunks=[]
    for start in range(0,min(limit,len(data['commands'])),chunk):
        commands=data['commands'][start:min(start+chunk,limit)];durations=[]
        lines=header(['A6.ReturnGenerated.Valid','A6.RLESound','A6.ReturnBridge'])
        for i,cmd in enumerate(commands,start):
            lines += [f'def before{i} (k : Nat) : Cfg := {cfg(cmd["before"])}',f'def after{i} (k : Nat) : Cfg := {cfg(cmd["after"])}']
            if cmd['kind']=='word':
                e=cmd['case'];dt=data['cases'][e][1][-1];count=nat_aff(cmd['count']);durations.append(f'({count}*{dt})')
                lines += [f'theorem macro{i} (k : Nat) : applyExit (before{i} k) exit{e} {count} = some (after{i} k) := by',f'  simp (disch := omega) [before{i}, after{i}, exit{e}, applyExit, pop, push]','  <;> omega',f'theorem step{i} (k : Nat) : Runs ({count}*{dt}) (before{i} k).denote (after{i} k).denote :=',f'  @applyExit_sound (before{i} k) (after{i} k) exit{e} {count} valid{e} (macro{i} k)']
            else:
                initial,steps,count=cycle_data(cmd,cases);kc=nat_aff(count);dt=cmd['certificate']['steps'];durations.append(f'({kc}*{dt})')
                lines += [f'def cycleState{i} (k j : Nat) : Cfg := {cfg(initial,True)}']
                for r,(_,after,e,n,_) in enumerate(steps[:-1]):lines += [f'def cyclePart{i}_{r} (k j : Nat) : Cfg := {cfg(after,True)}']
                for r,(bef,_,e,n,_) in enumerate(steps):
                    src=f'cycleState{i}' if r==0 else f'cyclePart{i}_{r-1}'
                    dst=f'cyclePart{i}_{r}' if r+1<len(steps) else f'cycleState{i}'
                    target=f'({dst} k j)' if r+1<len(steps) else f'({dst} k (j+1))'
                    lines += [f'theorem cycleMacro{i}_{r} (k j : Nat) (hj : j < {kc}) : applyExit ({src} k j) exit{e} {nat_aff2(n)} = some {target} := by']
                    source=bef['right'] if bef['d']==1 else bef['left']
                    guards=[]
                    if source:
                        c=source[-1][1]
                        lines += [f'  have hp : {nat_aff2(n)} ≤ {nat_aff2(c)} := by omega']
                        lines += [f'  have he : {nat_aff2(n)} '+('=' if n==c else '≠')+f' {nat_aff2(c)} := by omega']
                        lines += ['  simp only [Nat.one_mul] at hp he']
                        guards=['hp','he']
                    lines += [f'  simp (disch := omega) [{src}, {dst}, exit{e}, applyExit, pop, push'+(', '+', '.join(guards) if guards else '')+']','  <;> omega']
                lines += [f'theorem cycleRun{i} (k j : Nat) (hj : j < {kc}) : Runs {dt} (cycleState{i} k j).denote (cycleState{i} k (j+1)).denote := by']
                for r,(_,_,e,n,t) in enumerate(steps):
                    src=f'cycleState{i}' if r==0 else f'cyclePart{i}_{r-1}'
                    dst=f'cyclePart{i}_{r}' if r+1<len(steps) else f'cycleState{i}'
                    target=f'({dst} k j)' if r+1<len(steps) else f'({dst} k (j+1))'
                    lines += [f'  have h{r} : Runs ({nat_aff2(n)}*{t}) ({src} k j).denote {target}.denote := @applyExit_sound ({src} k j) {target} exit{e} {nat_aff2(n)} valid{e} (cycleMacro{i}_{r} k j hj)']
                rows=[]
                for r,(_,_,e,n,t) in enumerate(steps):
                    src=f'(cycleState{i} k j).denote' if r==0 else f'(cyclePart{i}_{r-1} k j).denote'
                    dst=f'(cyclePart{i}_{r} k j).denote' if r+1<len(steps) else f'(cycleState{i} k (j+1)).denote'
                    rows.append((f'({nat_aff2(n)}*{t})',src,dst,f'h{r}'))
                _,_,_,chain=compose(rows)
                lines += [f'  exact {chain}',f'theorem step{i} (k : Nat) : Runs ({kc}*{dt}) (before{i} k).denote (after{i} k).denote := by',f'  have h := Runs.chain (fun j => (cycleState{i} k j).denote) {dt} {kc} (cycleRun{i} k)',f'  have h0 : cycleState{i} k 0 = before{i} k := by simp [cycleState{i}, before{i}]',f'  have h1 : cycleState{i} k {kc} = after{i} k := by',f'    simp [cycleState{i}, after{i}] <;> omega','  simpa only [h0, h1] using h']
        end=start+len(commands)-1;duration=nat_aff(sub(commands[-1]['after']['steps'],commands[0]['before']['steps']));chunks.append((start,end,duration))
        lines += [f'theorem chunkRun{start//chunk:03} (k : Nat) : Runs {duration} (before{start} k).denote (after{end} k).denote := by']
        rows=[(duration,f'(before{i} k).denote',f'(after{i} k).denote',f'(step{i} k)') for i,duration in enumerate(durations,start)]
        timeexpr,_,_,chain=compose(rows)
        lines += [f'  have h := {chain}',f'  have ht : {timeexpr} = {duration} := by omega','  rw [ht] at h','  exact h'];write(f'Chunk{start//chunk:03}',lines)
    if limit>=len(data['commands']):
        lines=header([f'A6.ReturnGenerated.Chunk{i:03}' for i in range(len(chunks))])
        lines += ['theorem returnRun (k : Nat) : Runs (119808*k+304037417082) (initialCfg k).denote (endingCfg k).denote := by']
        rows=[(d,f'(before{start} k).denote',f'(after{end} k).denote',f'(chunkRun{i:03} k)') for i,(start,end,d) in enumerate(chunks)]
        timeexpr,_,_,chain=compose(rows)
        lines += [f'  have h := {chain}',f'  have ht : {timeexpr} = (119808*k+304037417082) := by omega','  rw [ht] at h','  exact h'];write('Return',lines)
    print({'words':len(WORDS),'pairs':len(pairs),'commands':min(limit,len(data['commands'])),'chunks':len(chunks)})

if __name__=='__main__':
    import sys
    main(int(sys.argv[1]) if len(sys.argv)>1 else 10000,int(sys.argv[2]) if len(sys.argv)>2 else 100)
